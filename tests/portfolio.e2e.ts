import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const evidence = process.env.EH_SCREENSHOTS
const invalid = '/projetos/inexistente/'
const github = 'https://api.github.com/users/Xit-coder/repos?*'
const sample = { name: 'Code-Atlas', html_url: 'https://github.com/Xit-coder/Code-Atlas', language: 'TypeScript', pushed_at: '2026-11-14T12:00:00Z', private: false }
async function reduced(page: Page) { await page.emulateMedia({ reducedMotion: 'reduce' }) }
async function screenshot(page: Page, name: string, fullPage = false) {
  if (evidence) await page.screenshot({ path: evidence + '/' + name + '.png', fullPage, animations: 'disabled' })
}

test('a introdução completa funciona no desktop e pode ser reproduzida na mesma sessão', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const intro = page.getByRole('dialog', { name: 'Introdução do portfólio' })
  await expect(intro).toBeVisible()
  await expect(intro.getByText('Connection established.', { exact: true })).toBeVisible()
  await screenshot(page, 'intro-boot')
  await expect(intro.getByText('visitor', { exact: true })).toBeVisible()
  await expect(intro.getByText('[ AUTHENTICATING ]')).toBeVisible()
  await screenshot(page, 'intro-auth')
  await expect(intro.getByText('ACCESS GRANTED')).toBeVisible()
  await expect(intro.locator('.intro-success')).toHaveCSS('opacity', '1')
  await screenshot(page, 'intro-access')
  await expect(intro).toBeHidden({ timeout: 7000 })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Erick Hatano.' })).toBeVisible()
  await expect(intro).toHaveCount(0)
  await page.getByRole('button', { name: 'Ver introdução', exact: true }).click()
  await expect(intro.getByText('Connection established.', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(intro).toHaveCount(0)
})
