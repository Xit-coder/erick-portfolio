test('GitHub exibe metadados públicos, reutiliza cache e trata indisponibilidade', async ({ page }) => {
  await reduced(page)
  let calls = 0
  await page.route(github, async route => { calls++; await route.fulfill({ json: [sample, { ...sample, name: 'privado', private: true }] }) })
  await page.goto('/')
  await page.getByText('Atividade no GitHub', { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Code-Atlas', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'privado' })).toHaveCount(0)
  await page.reload()
  await page.getByText('Atividade no GitHub', { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Code-Atlas', exact: true })).toBeVisible()
  expect(calls).toBe(1)
  await page.evaluate(() => localStorage.removeItem('eh-github-v1'))
  await page.unroute(github)
  await page.route(github, route => route.fulfill({ status: 429, json: {} }))
  await page.reload()
  await page.getByText('Atividade no GitHub', { exact: true }).click()
  await expect(page.getByText(/consulta está indisponível/)).toBeVisible()
})
test('links públicos, imagens e rotas de erro funcionam no build', async ({ page, request }) => {
  await reduced(page)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('404')) errors.push(message.text()) })
  await page.route(github, route => route.fulfill({ json: [sample] }))
  for (const slug of ['verta', 'codeatlas', 'discord-bot-premium', 'colombia-unveiled']) {
    const response = await page.goto('/projetos/' + slug + '/')
    expect(response?.ok()).toBe(true)
    await expect(page.locator('main h1')).toBeVisible()
    await expect.poll(() => page.locator('.gallery-image img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
    const images = await page.locator('main img').evaluateAll(items => [...new Set(items.map(img => (img as HTMLImageElement).getAttribute('src')))])
    for (const url of images) expect((await request.get(url!)).ok(), url!).toBe(true)
  }
  await page.goto('/projetos/codeatlas/')
  await expect(page.getByRole('link', { name: 'Repositório público' })).toHaveAttribute('href', 'https://github.com/Xit-coder/Code-Atlas')
  await expect(page.getByRole('link', { name: 'Ver demonstração' })).toHaveAttribute('href', 'https://codeatlas.erickhatano.workers.dev')
  expect(errors).toEqual([])
  const missing = await page.goto(invalid)
  expect(missing?.status()).toBe(404)
  await expect(page.getByRole('heading', { name: 'Página não encontrada.' })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar ao início', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Erick Hatano.' })).toBeVisible()
})

for (const width of [360, 390, 768, 1024, 1366, 1920, 2560]) {
  test('layout e navegação em ' + width + ' px', async ({ page }) => {
    await reduced(page)
    await page.setViewportSize({ width, height: width <= 768 ? 844 : 900 })
    await page.route(github, route => route.fulfill({ json: [sample] }))
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Erick Hatano.' })).toBeVisible()
    const image = page.locator('img[fetchpriority=high]').first()
    await expect.poll(() => image.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await screenshot(page, 'inicio-' + width, [390, 1366].includes(width))
    if (width <= 900) await page.getByRole('button', { name: 'Abrir menu', exact: true }).click()
    await page.getByRole('navigation').getByRole('link', { name: 'Sobre mim' }).click()
    await expect(page).toHaveURL(/#sobre$/)
    await page.goto('/projetos/colombia-unveiled/')
    await expect(page.locator('main h1')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  })
}
